import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

export const repoRoot = path.resolve(here, '../..');
export const designTokensRoot = path.join(repoRoot, 'design-tokens');
export const designTokensSrcRoot = path.join(designTokensRoot, 'src');
export const tokenSourceRoot = path.join(designTokensSrcRoot, 'tokens');
export const recipeSourceRoot = path.join(designTokensSrcRoot, 'recipes');

export const tokenFilesGlob = 'design-tokens/src/tokens/**/*.tokens.json';
export const recipeFilesGlob = 'design-tokens/src/recipes/*.recipe.json';

export const themeRegistryPath = path.join(tokenSourceRoot, 'themes/registry.json');
export const recipeSchemaPath = path.join(recipeSourceRoot, 'schema/recipe.schema.json');
export const pilotComponentsPath = path.join(recipeSourceRoot, 'pilot-components.json');
export const runtimeInventoryPath = path.join(
  tokenSourceRoot,
  'migrations/runtime-variable-inventory.json'
);
export const runtimeAliasMapPath = path.join(
  tokenSourceRoot,
  'migrations/runtime-css-aliases.json'
);

export const distRoot = path.join(designTokensRoot, 'dist');
export const stagedRuntimeCssPath = path.join(distRoot, 'css/tokens.css');
export const typedTokensPath = path.join(distRoot, 'tokens.ts');
export const figmaTokensPath = path.join(distRoot, 'figma/tokens.json');
export const runtimeCssPath = path.join(repoRoot, 'src/lib/tokens/tokens.css');

export const generatedFileBanner =
  '/* This file is generated by pnpm build:tokens. Do not edit by hand. */';

const buildArtifactDefinitions = [
  ['runtime-css', 'css', 'src/lib/tokens/tokens.css', runtimeCssPath],
  ['typed-tokens', 'typescript', 'design-tokens/dist/tokens.ts', typedTokensPath],
  ['figma-tokens', 'json', 'design-tokens/dist/figma/tokens.json', figmaTokensPath],
];

const buildWriteTargetDefinitions = [
  ['runtime-css-stage', 'css', 'design-tokens/dist/css/tokens.css', stagedRuntimeCssPath],
  ...buildArtifactDefinitions,
];

export function getBuildArtifacts(options = {}) {
  return materializeArtifactDefinitions(buildArtifactDefinitions, options);
}

export function getBuildWriteTargets(options = {}) {
  return materializeArtifactDefinitions(buildWriteTargetDefinitions, options);
}

export function createBuildArtifactPathOverrides(tempRoot) {
  const outputRoot = path.resolve(tempRoot);

  return {
    stagedRuntimeCssPath: path.join(outputRoot, 'design-tokens/dist/css/tokens.css'),
    runtimeCssPath: path.join(outputRoot, 'src/lib/tokens/tokens.css'),
    typedTokensPath: path.join(outputRoot, 'design-tokens/dist/tokens.ts'),
    figmaTokensPath: path.join(outputRoot, 'design-tokens/dist/figma/tokens.json'),
  };
}

export function getArtifactContractRule(artifactId) {
  return artifactId === 'runtime-css' ? 'CT-6' : 'CT-5';
}

export const buildArtifacts = getBuildArtifacts();
export const buildWriteTargets = getBuildWriteTargets();

export function toRepoRelative(filePath) {
  return path.relative(repoRoot, filePath).replaceAll(path.sep, '/');
}

function materializeArtifactDefinitions(definitions, options) {
  return definitions.map(([id, kind, relPath, absPath]) => ({
    id,
    kind,
    relPath,
    absPath: resolveArtifactPath(id, absPath, options),
  }));
}

function resolveArtifactPath(id, fallbackPath, options) {
  if (id === 'runtime-css-stage') {
    return options.stagedRuntimeCssPath ?? fallbackPath;
  }
  if (id === 'runtime-css') {
    return options.runtimeCssPath ?? fallbackPath;
  }
  if (id === 'typed-tokens') {
    return options.typedTokensPath ?? fallbackPath;
  }
  if (id === 'figma-tokens') {
    return options.figmaTokensPath ?? fallbackPath;
  }
  return fallbackPath;
}
